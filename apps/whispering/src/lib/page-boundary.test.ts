/**
 * What the page may import.
 *
 * The page runs in a WebView and in a browser tab, so nothing under `src/` may
 * reach a native module: not the native folder opener, not Node or Bun, and
 * not a Tauri API. The recording workflow is file-backed, so it may not reach
 * the Yjs store either. This reads the sources, so a violation names its file.
 */
import { expect, test } from 'bun:test';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = fileURLToPath(new URL('..', import.meta.url));

/** Generated by the Epicenter host's build for its own tests; nothing here imports it. */
const GENERATED = 'lib/tauri/bindings.gen.ts';

function* sources(directory: string): Generator<string> {
	for (const name of readdirSync(directory)) {
		const path = join(directory, name);
		if (statSync(path).isDirectory()) yield* sources(path);
		else if (
			/\.(ts|svelte)$/.test(name) &&
			!/\.test(-support)?\.ts$/.test(name)
		)
			yield path;
	}
}

const IMPORT = /(?:from\s+|import\s*\(\s*|import\s+)['"]([^'"]+)['"]/g;

const files = [...sources(src)]
	.map((path) => ({
		path: relative(src, path),
		text: readFileSync(path, 'utf8'),
	}))
	.filter((file) => file.path !== GENERATED);

function importers(matches: (specifier: string) => boolean) {
	const found: string[] = [];
	for (const file of files)
		for (const [, specifier] of file.text.matchAll(IMPORT))
			if (specifier !== undefined && matches(specifier))
				found.push(`${file.path} imports ${specifier}`);
	return found;
}

test('the page imports no native module', () => {
	expect(
		importers(
			(specifier) =>
				specifier.startsWith('node:') ||
				specifier.startsWith('bun') ||
				specifier.startsWith('@tauri-apps/') ||
				specifier === '@epicenter/app/files/native' ||
				specifier.includes('/native/'),
		),
	).toEqual([]);
});

test('the page imports no Yjs store, sync, or account module', () => {
	expect(
		importers(
			(specifier) =>
				specifier === 'yjs' ||
				specifier.startsWith('@y/') ||
				specifier.startsWith('@epicenter/sync') ||
				specifier.startsWith('@epicenter/svelte') ||
				specifier.startsWith('@epicenter/auth') ||
				specifier.startsWith('@epicenter/blobs') ||
				specifier.startsWith('@epicenter/recorder') ||
				[
					'@epicenter/app/open',
					'@epicenter/app/store',
					'@epicenter/app/sync',
					'@epicenter/app/data',
					'@epicenter/app/memory',
					'@epicenter/app/blobs',
					'@epicenter/app/recorder',
				].includes(specifier),
		),
	).toEqual([]);
});

test('nothing imports the generated host bindings', () => {
	expect(importers((specifier) => specifier.includes('bindings.gen'))).toEqual(
		[],
	);
});
